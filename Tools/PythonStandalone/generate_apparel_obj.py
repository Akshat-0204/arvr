#!/usr/bin/env python3
"""
generate_apparel_obj.py
Procedural 3D Apparel Wavefront OBJ Generator for MerchAR.
Generates 3D T-Shirt and Hoodie models with UVs and Normals without needing Blender.
Can be executed with standard Python 3 (pure standard library, zero external pip packages).
"""

import os
import math

def calculate_normal(p1, p2, p3):
    ux, uy, uz = p2[0] - p1[0], p2[1] - p1[1], p2[2] - p1[2]
    vx, vy, vz = p3[0] - p1[0], p3[1] - p1[1], p3[2] - p1[2]
    nx = uy * vz - uz * vy
    ny = uz * vx - ux * vz
    nz = ux * vy - uy * vx
    length = math.sqrt(nx * nx + ny * ny + nz * nz)
    if length > 1e-6:
        return (nx / length, ny / length, nz / length)
    return (0.0, 1.0, 0.0)

class ObjMeshBuilder:
    def __init__(self, name="Mesh"):
        self.name = name
        self.vertices = []      # list of (x, y, z)
        self.uvs = []           # list of (u, v)
        self.normals = []       # list of (nx, ny, nz)
        self.faces = []         # list of list of (v_idx, uv_idx, norm_idx) 1-based

    def add_vertex(self, x, y, z):
        self.vertices.append((x, y, z))
        return len(self.vertices)

    def add_uv(self, u, v):
        self.uvs.append((u, v))
        return len(self.uvs)

    def add_normal(self, nx, ny, nz):
        self.normals.append((nx, ny, nz))
        return len(self.normals)

    def add_quad(self, v1, v2, v3, v4, uv1, uv2, uv3, uv4):
        # Calculate surface normal
        p1 = self.vertices[v1 - 1]
        p2 = self.vertices[v2 - 1]
        p3 = self.vertices[v3 - 1]
        norm = calculate_normal(p1, p2, p3)
        n_idx = self.add_normal(*norm)
        
        # Split quad into 2 triangles: (v1, v2, v3) and (v1, v3, v4)
        self.faces.append([(v1, uv1, n_idx), (v2, uv2, n_idx), (v3, uv3, n_idx)])
        self.faces.append([(v1, uv1, n_idx), (v3, uv3, n_idx), (v4, uv4, n_idx)])

    def add_triangle(self, v1, v2, v3, uv1, uv2, uv3):
        p1 = self.vertices[v1 - 1]
        p2 = self.vertices[v2 - 1]
        p3 = self.vertices[v3 - 1]
        norm = calculate_normal(p1, p2, p3)
        n_idx = self.add_normal(*norm)
        self.faces.append([(v1, uv1, n_idx), (v2, uv2, n_idx), (v3, uv3, n_idx)])

    def export_obj(self, filepath, mtl_name=None):
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, "w") as f:
            f.write(f"# Wavefront OBJ generated by MerchAR Procedural Generator\n")
            f.write(f"o {self.name}\n")
            if mtl_name:
                f.write(f"mtllib {mtl_name}.mtl\n")
                f.write(f"usemtl {mtl_name}\n")
            
            for v in self.vertices:
                f.write(f"v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n")
            
            for uv in self.uvs:
                f.write(f"vt {uv[0]:.4f} {uv[1]:.4f}\n")
            
            for n in self.normals:
                f.write(f"vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}\n")
            
            for face in self.faces:
                f.write("f " + " ".join(f"{idx[0]}/{idx[1]}/{idx[2]}" for idx in face) + "\n")
        print(f"Exported {self.name} to {filepath} ({len(self.vertices)} verts, {len(self.faces)} tris)")

def generate_tshirt_mesh():
    builder = ObjMeshBuilder("TShirt")
    
    # Grid parameters for torso cylinder
    rings = 10
    segments = 24
    
    # Torso profile height from -0.4 to +0.35 (meters)
    y_min = -0.40
    y_max = 0.35
    
    grid = [] # grid[r][s] = (v_idx, uv_idx)
    
    for r in range(rings):
        row = []
        t = r / (rings - 1)
        y = y_min + t * (y_max - y_min)
        
        # Contour width (chest is wider, waist slightly tapered, neck narrows)
        if t < 0.2:
            rx = 0.22 + t * 0.02
            rz = 0.12 + t * 0.01
        elif t < 0.7:
            rx = 0.23 + (t - 0.2) * 0.06
            rz = 0.125 + (t - 0.2) * 0.03
        else: # shoulders/neck
            rx = 0.26 - (t - 0.7) * 0.25
            rz = 0.14 - (t - 0.7) * 0.18
            
        for s in range(segments):
            angle = (s / segments) * 2.0 * math.pi
            
            # Flatter front & back, rounded sides
            cos_a = math.cos(angle)
            sin_a = math.sin(angle)
            
            x = cos_a * rx
            z = sin_a * rz
            
            # Collar indentation at upper front
            if t > 0.8 and -0.4 < sin_a < 0.4 and cos_a > 0:
                y_adj = y - 0.05 * (1.0 - abs(sin_a) * 2.5)
            else:
                y_adj = y
                
            u = s / segments
            v = t
            v_idx = builder.add_vertex(x, y_adj, z)
            uv_idx = builder.add_uv(u, v)
            row.append((v_idx, uv_idx))
        grid.append(row)
        
    # Torso faces
    for r in range(rings - 1):
        for s in range(segments):
            next_s = (s + 1) % segments
            v1, uv1 = grid[r][s]
            v2, uv2 = grid[r][next_s]
            v3, uv3 = grid[r + 1][next_s]
            v4, uv4 = grid[r + 1][s]
            builder.add_quad(v1, v2, v3, v4, uv1, uv2, uv3, uv4)
            
    # Add Sleeves (Left & Right)
    def add_sleeve(side_sign):
        sleeve_segments = 12
        sleeve_rings = 6
        sleeve_grid = []
        
        shoulder_x = side_sign * 0.25
        shoulder_y = 0.25
        shoulder_z = 0.0
        
        length = 0.22
        radius_base = 0.085
        radius_cuff = 0.075
        
        for r in range(sleeve_rings):
            t = r / (sleeve_rings - 1)
            # Arm angles slightly down and slightly forward
            cx = shoulder_x + side_sign * (t * length * 0.85)
            cy = shoulder_y - (t * length * 0.50)
            cz = shoulder_z + (t * length * 0.15)
            rad = radius_base * (1.0 - t * 0.12)
            
            row = []
            for s in range(sleeve_segments):
                angle = (s / sleeve_segments) * 2.0 * math.pi
                # Orthogonal circle around arm direction
                dx = math.sin(angle) * rad * 0.5
                dy = math.cos(angle) * rad
                dz = math.sin(angle) * rad * 0.86
                
                v_idx = builder.add_vertex(cx + dx, cy + dy, cz + dz)
                uv_idx = builder.add_uv(s / sleeve_segments, t)
                row.append((v_idx, uv_idx))
            sleeve_grid.append(row)
            
        for r in range(sleeve_rings - 1):
            for s in range(sleeve_segments):
                next_s = (s + 1) % sleeve_segments
                v1, uv1 = sleeve_grid[r][s]
                v2, uv2 = sleeve_grid[r][next_s]
                v3, uv3 = sleeve_grid[r + 1][next_s]
                v4, uv4 = sleeve_grid[r + 1][s]
                if side_sign > 0:
                    builder.add_quad(v1, v2, v3, v4, uv1, uv2, uv3, uv4)
                else:
                    builder.add_quad(v1, v4, v3, v2, uv1, uv4, uv3, uv2)

    add_sleeve(1.0)   # Right sleeve
    add_sleeve(-1.0)  # Left sleeve
    
    # Neck Collar Ring
    collar_segs = 16
    c_inner = []
    c_outer = []
    cy = 0.33
    for i in range(collar_segs):
        ang = (i / collar_segs) * 2.0 * math.pi
        rx_in, rz_in = 0.09 * math.cos(ang), 0.07 * math.sin(ang)
        rx_out, rz_out = 0.11 * math.cos(ang), 0.09 * math.sin(ang)
        v_in = builder.add_vertex(rx_in, cy, rz_in)
        uv_in = builder.add_uv(i / collar_segs, 0.0)
        v_out = builder.add_vertex(rx_out, cy + 0.02, rz_out)
        uv_out = builder.add_uv(i / collar_segs, 1.0)
        c_inner.append((v_in, uv_in))
        c_outer.append((v_out, uv_out))
        
    for i in range(collar_segs):
        ni = (i + 1) % collar_segs
        builder.add_quad(c_inner[i][0], c_outer[i][0], c_outer[ni][0], c_inner[ni][0],
                         c_inner[i][1], c_outer[i][1], c_outer[ni][1], c_inner[ni][1])
        
    return builder

def generate_hoodie_mesh():
    builder = ObjMeshBuilder("Hoodie")
    
    # Slightly bulkier torso with thicker waistband
    rings = 11
    segments = 24
    y_min = -0.42
    y_max = 0.36
    grid = []
    
    for r in range(rings):
        row = []
        t = r / (rings - 1)
        y = y_min + t * (y_max - y_min)
        
        # Thicker streetwear oversize silhouette
        if t < 0.12: # Ribbed bottom band
            rx = 0.23
            rz = 0.13
        elif t < 0.7:
            rx = 0.25 + (t - 0.12) * 0.05
            rz = 0.145 + (t - 0.12) * 0.03
        else:
            rx = 0.27 - (t - 0.7) * 0.24
            rz = 0.16 - (t - 0.7) * 0.17
            
        for s in range(segments):
            angle = (s / segments) * 2.0 * math.pi
            x = math.cos(angle) * rx
            z = math.sin(angle) * rz
            u = s / segments
            v = t
            v_idx = builder.add_vertex(x, y, z)
            uv_idx = builder.add_uv(u, v)
            row.append((v_idx, uv_idx))
        grid.append(row)
        
    for r in range(rings - 1):
        for s in range(segments):
            next_s = (s + 1) % segments
            v1, uv1 = grid[r][s]
            v2, uv2 = grid[r][next_s]
            v3, uv3 = grid[r + 1][next_s]
            v4, uv4 = grid[r + 1][s]
            builder.add_quad(v1, v2, v3, v4, uv1, uv2, uv3, uv4)
            
    # Kangaroo Pocket on Front
    # Front is facing +Z or +X depending on angle (here front is cos_a > 0, angle ~ 0)
    # Let's add kangaroo pouch vertices on the lower abdomen
    kp_v1 = builder.add_vertex(0.12, -0.28, 0.15)
    kp_v2 = builder.add_vertex(-0.12, -0.28, 0.15)
    kp_v3 = builder.add_vertex(-0.10, -0.10, 0.16)
    kp_v4 = builder.add_vertex(0.10, -0.10, 0.16)
    
    uv_kp1 = builder.add_uv(0.3, 0.2)
    uv_kp2 = builder.add_uv(0.7, 0.2)
    uv_kp3 = builder.add_uv(0.65, 0.5)
    uv_kp4 = builder.add_uv(0.35, 0.5)
    builder.add_quad(kp_v1, kp_v2, kp_v3, kp_v4, uv_kp1, uv_kp2, uv_kp3, uv_kp4)
    
    # Long Sleeves with wrist cuffs
    def add_long_sleeve(side_sign):
        sleeve_segments = 12
        sleeve_rings = 9
        sleeve_grid = []
        
        shoulder_x = side_sign * 0.26
        shoulder_y = 0.26
        shoulder_z = 0.0
        
        length = 0.44 # Longer for hoodie
        radius_base = 0.095
        radius_cuff = 0.065
        
        for r in range(sleeve_rings):
            t = r / (sleeve_rings - 1)
            cx = shoulder_x + side_sign * (t * length * 0.70)
            cy = shoulder_y - (t * length * 0.75)
            cz = shoulder_z + (t * length * 0.15)
            rad = radius_base - t * (radius_base - radius_cuff)
            
            row = []
            for s in range(sleeve_segments):
                angle = (s / sleeve_segments) * 2.0 * math.pi
                dx = math.sin(angle) * rad * 0.5
                dy = math.cos(angle) * rad
                dz = math.sin(angle) * rad * 0.86
                
                v_idx = builder.add_vertex(cx + dx, cy + dy, cz + dz)
                uv_idx = builder.add_uv(s / sleeve_segments, t)
                row.append((v_idx, uv_idx))
            sleeve_grid.append(row)
            
        for r in range(sleeve_rings - 1):
            for s in range(sleeve_segments):
                next_s = (s + 1) % sleeve_segments
                v1, uv1 = sleeve_grid[r][s]
                v2, uv2 = sleeve_grid[r][next_s]
                v3, uv3 = sleeve_grid[r + 1][next_s]
                v4, uv4 = sleeve_grid[r + 1][s]
                if side_sign > 0:
                    builder.add_quad(v1, v2, v3, v4, uv1, uv2, uv3, uv4)
                else:
                    builder.add_quad(v1, v4, v3, v2, uv1, uv4, uv3, uv2)

    add_long_sleeve(1.0)
    add_long_sleeve(-1.0)
    
    # 3D Sculpted Hood draped around neck and resting behind head
    hood_rings = 8
    hood_segments = 14
    hood_grid = []
    
    for r in range(hood_rings):
        row = []
        t = r / (hood_rings - 1)
        # Curves up from neckline (y=0.34) around back of head and over top
        hy = 0.32 + math.sin(t * math.pi * 0.85) * 0.22
        hz = -0.06 - math.cos(t * math.pi * 0.85) * 0.16
        hr = 0.15 * math.sin(t * math.pi * 0.9 + 0.15) + 0.05
        
        for s in range(hood_segments):
            frac = s / (hood_segments - 1)
            # Arch from left to right over head/neck
            angle = (frac - 0.5) * math.pi * 1.1
            hx = math.sin(angle) * hr * 1.3
            hy_adj = hy + math.cos(angle) * hr * 0.6
            
            v_idx = builder.add_vertex(hx, hy_adj, hz)
            uv_idx = builder.add_uv(frac, t)
            row.append((v_idx, uv_idx))
        hood_grid.append(row)
        
    for r in range(hood_rings - 1):
        for s in range(hood_segments - 1):
            v1, uv1 = hood_grid[r][s]
            v2, uv2 = hood_grid[r][s + 1]
            v3, uv3 = hood_grid[r + 1][s + 1]
            v4, uv4 = hood_grid[r + 1][s]
            builder.add_quad(v1, v2, v3, v4, uv1, uv2, uv3, uv4)
            
    # Drawstrings dangling in front
    for side in [-0.04, 0.04]:
        for seg in range(4):
            dy = -seg * 0.04
            p1 = builder.add_vertex(side, 0.26 + dy, 0.13)
            p2 = builder.add_vertex(side + 0.008, 0.26 + dy, 0.13)
            p3 = builder.add_vertex(side + 0.008, 0.22 + dy, 0.13)
            p4 = builder.add_vertex(side, 0.22 + dy, 0.13)
            builder.add_quad(p1, p2, p3, p4, 0, 0, 0, 0)
            
    return builder

def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out_dir = os.path.join(base_dir, "Assets", "Models", "Generated")
    os.makedirs(out_dir, exist_ok=True)
    
    tshirt = generate_tshirt_mesh()
    tshirt.export_obj(os.path.join(out_dir, "TShirt.obj"), "M_TShirt_Default")
    
    hoodie = generate_hoodie_mesh()
    hoodie.export_obj(os.path.join(out_dir, "Hoodie.obj"), "M_Hoodie_Default")
    
    print("All models generated successfully without Blender!")

if __name__ == "__main__":
    main()
